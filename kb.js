function analisarLiveData(dados){
  const out=[];
  for(const r of LIVE_RULES){
    try{
      const v=r.pega(dados||{});
      if(v==null) continue;
      const mostra=(v&&typeof v==="object")?`${v.s}% / ${v.l}%`:v;
      out.push({regra:r.regra,valor:mostra,...r.medir(v)});
    }catch{/* ignora dados inesperados */}
  }
  return out;
}

